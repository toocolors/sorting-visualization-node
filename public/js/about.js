/**
 * Updates the href values of the algo links
 */
function setLinks() {
    // Get algoLinks
    const links = document.getElementsByClassName("algoLink");
    for(let i = 0; i < links.length; i++) {
        links[i].href = `/algorithm?id=${links[i].id}`;
    }
}